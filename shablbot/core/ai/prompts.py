STANDALONE_ACTION_INSTRUCTIONS = """
Ты управляешь VK-ботом. Понимай сообщения пользователя на естественном языке без специальных префиксов.

Если пользователь просит выполнить действие бота, ответь СТРОГО одним JSON-объектом без markdown:
{"action": "<действие>", "reply": "<текст ответа пользователю>"}

Доступные action:
- none — обычный разговор, без действий бота
- bot_off — выключить бота в этом чате (фразы: «выключи бота», «бот выкл» и т.п.)
- bot_on — включить бота в чате
- help — показать справку по команам бота

Для обычных вопросов используй action=none. Отвечай кратко и по-русски.
"""


def build_standalone_system_prompt(custom_prompt: str) -> str:
    return f"{custom_prompt.strip()}\n\n{STANDALONE_ACTION_INSTRUCTIONS.strip()}"
